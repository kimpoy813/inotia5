import { readdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { join } from 'node:path'
const dist=new URL('../dist/',import.meta.url)
async function tree(root=''){
  const files=await readdir(new URL(root,dist),{withFileTypes:true})
  return (await Promise.all(files.filter(d=>d.name!=='sw.js').map(d=>d.isDirectory()?tree(`${join(root,d.name)}/`):join(root,d.name)))).flat()
}
const files=(await tree()).sort(),hash=createHash('sha256')
for(const f of files)hash.update(await readFile(new URL(f,dist)))
const name=`veilbound-${hash.digest('hex').slice(0,14)}`
await writeFile(new URL('sw.js',dist),`/* Generated by the production build. */
const VERSION=${JSON.stringify(name)};
const FILES=${JSON.stringify(files.map(p=>`/${p}`))};
self.addEventListener('install', e=>e.waitUntil(caches.open(VERSION).then(c=>c.addAll(FILES))));
self.addEventListener('activate', e=>e.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('veilbound-')&&k!==VERSION).map(k=>caches.delete(k)))).then(()=>self.clients.claim())));
self.addEventListener('fetch', e=>{
  const u=new URL(e.request.url);
  if(u.origin!==self.location.origin||e.request.method!=='GET')return;
  if(e.request.mode==='navigate') {
    // Keep this HTML and all its lazy chunks on the same release until the new worker activates.
    e.respondWith(caches.open(VERSION).then(c=>c.match('/index.html')).then(res=>res||fetch(e.request)));
  } else if(FILES.includes(u.pathname)) {
    e.respondWith(caches.open(VERSION).then(c=>c.match(u.pathname)).then(res=>res||fetch(e.request)));
  }
});
`)
console.log(`Verified ${files.length} local precache entries for ${name}`)
